"""Синхронизировать новую основную сетку и справочник стран с браузером."""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def render():
    from src.classification_runtime import taxonomy, policy

    data = taxonomy()
    data["enabled"] = policy()["enabled"]
    countries = json.loads(
        (ROOT / "config/countries_v11.json").read_text(encoding="utf-8")
    )
    data["country_labels"] = {c["country"]: c["label"] for c in countries["countries"]}
    notice = (ROOT / "docs/licenses/UNICODE.txt").read_text(encoding="utf-8")
    return (
        "// Generated by python scripts/sync_classification_v11.py\n/* Country-name data: Unicode CLDR 48.\n"
        + notice
        + "\n*/\nwindow.TG_CLASSIFICATION_V11 = "
        + json.dumps(data, ensure_ascii=False, indent=2).replace("<", "\\u003c")
        + ";\n"
    )


if __name__ == "__main__":
    from src.file_io import atomic_write_text

    atomic_write_text(ROOT / "web/classification-v11-taxonomy.js", render())
