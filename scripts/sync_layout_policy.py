"""Синхронизировать декларативную политику размещения с браузером."""

import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))


def render():
    from src.layout_policy import load_policy,policy_fingerprint
    policy=load_policy()
    return '// Generated by python scripts/sync_layout_policy.py\nwindow.TG_MAP_POLICY = '+json.dumps(
        dict(policy,fingerprint=policy_fingerprint(policy)),ensure_ascii=False,indent=2)+';\n'


if __name__=='__main__':
    from src.file_io import atomic_write_text
    atomic_write_text(ROOT/'web/layout-policy.js',render())
