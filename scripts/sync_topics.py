"""Generate browser taxonomy from the same files used by the API. No dependencies."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def render():
    sys.path.insert(0, str(ROOT))
    from src.region_aliases import REGION_ALIASES
    from src.region_geo import FEDERAL_SUBJECTS
    from src.build_geo_map import project_lcc

    data = json.loads((ROOT / "config/topics.json").read_text(encoding="utf-8"))
    data["overrides"] = json.loads(
        (ROOT / "config/topic_overrides.json").read_text(encoding="utf-8")
    )
    data["geography_overrides"] = json.loads(
        (ROOT / "config/geography_overrides.json").read_text(encoding="utf-8")
    )
    labels = json.loads(
        (ROOT / "config/classification_labels.json").read_text(encoding="utf-8")
    )["channels"]
    data["overrides"].update({u: v["topic"] for u, v in labels.items()})
    data["geography_overrides"].update(
        {
            u: {k: v[k] for k in ("scope", "regions", "country")}
            for u, v in labels.items()
        }
    )
    data["tag_overrides"] = {
        u: v.get("secondary_topics", []) for u, v in labels.items()
    }
    data["foreign_geography"] = json.loads(
        (ROOT / "config/foreign_geography.json").read_text(encoding="utf-8")
    )
    data["region_aliases"] = REGION_ALIASES
    data["region_centers"] = {
        name: list(project_lcc(*coords)) for name, coords in FEDERAL_SUBJECTS.items()
    }
    data["federal_channels"] = json.loads(
        (ROOT / "config/federal_channels.json").read_text(encoding="utf-8")
    )["channels"]
    return (
        "// Generated by python scripts/sync_topics.py; edit config/topics.json instead.\nwindow.TG_TAXONOMY = "
        + json.dumps(data, ensure_ascii=False, indent=2)
        + ";\n"
    )


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    from src.file_io import atomic_write_text

    atomic_write_text(ROOT / "web/taxonomy.js", render())
