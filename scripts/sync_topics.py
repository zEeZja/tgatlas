"""Generate browser taxonomy from the same files used by the API. No dependencies."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def render():
    data = json.loads((ROOT / 'config/topics.json').read_text(encoding='utf-8'))
    data['overrides'] = json.loads((ROOT / 'config/topic_overrides.json').read_text(encoding='utf-8'))
    return '// Generated by python scripts/sync_topics.py; edit config/topics.json instead.\nwindow.TG_TAXONOMY = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'

if __name__ == '__main__':
    (ROOT / 'web/taxonomy.js').write_text(render(), encoding='utf-8')
