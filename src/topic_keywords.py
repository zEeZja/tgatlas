"""Explainable topic classification shared by export and HTTP API.

Rules live in config/topics.json; browser rules are generated by scripts/sync_topics.py.
Scores are evidence weights, never probabilities. Generic legacy labels may be refined;
explicit specialised labels and config/topic_overrides.json take priority.
"""

from __future__ import annotations

import json
import re
import unicodedata
from functools import lru_cache
from pathlib import Path
from .geography import resolve_geography
from .title_region import local_news_evidence
from .classification_text import informative_description

ROOT = Path(__file__).resolve().parent.parent
TAXONOMY = json.loads((ROOT / "config/topics.json").read_text(encoding="utf-8"))
TOPICS = {t["id"]: t for t in TAXONOMY["topics"]}
GROUPS = {g["id"]: g for g in TAXONOMY["groups"]}
TOPIC_LABELS = {key: t["label"] for key, t in TOPICS.items()}
TOPIC_KEYWORDS = {key: t["keywords"] for key, t in TOPICS.items()}


@lru_cache(maxsize=8192)
def _normalize(value: str | None) -> str:
    text = unicodedata.normalize("NFKC", str(value or "")).casefold().replace("ё", "е")
    return re.sub(r"[^\w]+|_", " ", text, flags=re.UNICODE).strip()


def canonical(value: str | None) -> str:
    key = str(value or "").strip().lower()
    return TAXONOMY["aliases"].get(key, key)


@lru_cache(maxsize=4096)
def _word_tokens(text: str) -> tuple[str, ...]:
    return tuple(text.split())


def _matches(keyword: str, text: str, field: str) -> bool:
    pattern = _normalize(keyword)
    if " " in pattern:
        return f" {pattern} " in f" {text} "
    # Short terms must be whole tokens: art/party/car/eth should not match arbitrary words.
    for token in _word_tokens(text):
        if keyword == "авто" and token.startswith(
            ("автомат", "автор", "автоном", "автопортрет")
        ):
            continue
        if keyword == "искусств" and token.startswith("искусствен"):
            continue
        if keyword == "новост" and token.startswith("новостро"):
            continue
        if token == pattern or (
            len(pattern) >= (5 if pattern.isascii() else 4)
            and token.startswith(pattern)
        ):
            return True
        if (
            field == "username"
            and len(pattern) >= 5
            and pattern.isascii()
            and token.endswith(pattern)
        ):
            if pattern == "sport" and token.endswith(("transport", "passport")):
                continue
            return True
    return False


def classify_topic(
    name: str = "", username: str = "", description: str = "", threshold: float = 3.0
) -> dict:
    fields = [
        ("name", _normalize(name), 4),
        ("username", _normalize(username), 3),
        ("description", _normalize(informative_description(description)), 2),
    ]
    ranked = []
    strong_description = set()
    for topic in TAXONOMY["topics"]:
        profile_fields = fields[0:1] + fields[2:3]
        if any(_matches(k, text, field) for field, text, _ in profile_fields
               for k in topic.get("exclude_phrases", [])):
            continue
        prefix = any((fields[0][1] + " ").startswith(_normalize(p) + " ")
                     for p in topic.get("name_prefixes", []))
        if topic.get("require_any") and not prefix and not any(
                _matches(k, text, field) for field, text, _ in profile_fields
                for k in topic["require_any"]):
            continue
        score = 0
        evidence = []
        for field, text, weight in fields:
            matches = [k for k in topic["keywords"] if _matches(k, text, field)]
            # Cap each field so repetition and keyword stuffing cannot dominate.
            if matches:
                score += weight * min(len(matches), 3)
                evidence.extend(f"{field}:{k}" for k in matches[:3])
        if prefix and not score:
            score = 4
            evidence.append("name:наименование органа власти")
        if any(
            _matches(k, fields[-1][1], "description")
            for k in topic.get("strong_description_keywords", [])
        ):
            strong_description.add(topic["id"])
        if topic["id"] == "general":
            score *= 0.5  # "news" in a political/scientific channel is a format, not its subject.
        if score:
            ranked.append(dict(id=topic["id"], score=score, evidence=evidence))
    ranked.sort(key=lambda t: (-t["score"], t["id"]))
    qualified = [
        r
        for r in ranked
        if r["score"]
        >= (
            min(threshold, 2)
            if r["id"] == "general" or r["id"] in strong_description
            else threshold
        )
    ]
    qualified = [
        r
        for r in qualified
        if not any(r["id"] in TOPICS[c["id"]].get("refines", []) for c in qualified)
    ]
    best = (
        qualified[0]
        if qualified
        else ranked[0]
        if ranked
        else dict(id="other", score=0, evidence=[])
    )
    winner = best["id"] if qualified else "other"
    contextual = local_news_evidence(name, description) if winner == "other" else None
    if contextual:
        winner = "general"
        best = dict(id="general", score=3, evidence=[contextual])
    candidates = [dict(id=t["id"], score=t["score"]) for t in ranked[:3]]
    ambiguous = (
        len(qualified) > 1
        and qualified[1]["id"] != "general"
        and best["score"] - qualified[1]["score"] < 2
    )
    return dict(
        subcategory=winner,
        score=best["score"],
        evidence=best["evidence"],
        candidates=candidates,
        tags=[
            r["id"]
            for r in qualified
            if r["id"] != winner
            and r["id"] != "general"
            and r["score"] >= max(3, best["score"] * 0.6)
        ][:3],
        review_required=winner == "other"
        or ambiguous
        or bool(contextual and "требует проверки" in contextual),
    )


def load_classification_rules():
    """Read one consistent rule snapshot per export/audit/API request."""

    def read(name):
        return json.loads((ROOT / "config" / name).read_text(encoding="utf-8"))

    labels = read("classification_labels.json")["channels"]
    return dict(
        overrides={
            **read("topic_overrides.json"),
            **{u: v["topic"] for u, v in labels.items() if "topic" in v},
        },
        geography_overrides={
            **read("geography_overrides.json"),
            **{
                u: {k: v[k] for k in ("scope", "regions", "country")}
                for u, v in labels.items() if all(k in v for k in ("scope", "regions", "country"))
            },
        },
        review_metadata={
            u: v["reviewed_profile"]
            for u, v in labels.items()
            if "reviewed_profile" in v
        },
        format_overrides={u: v["formats"] for u, v in labels.items() if "formats" in v},
        group_overrides={
            u: v.get("group", TOPICS[v["topic"]]["group"]) for u, v in labels.items() if "topic" in v
        },
        tag_overrides={u: v.get("secondary_topics", []) for u, v in labels.items() if "topic" in v},
        federal_channels=frozenset(
            x.lower() for x in read("federal_channels.json")["channels"]
        ),
    )


def resolve_topic(
    channel: dict,
    overrides: dict | None = None,
    *,
    geography_overrides=None,
    federal_channels=None,
    tag_overrides=None,
    group_overrides=None,
    format_overrides=None,
    review_metadata=None,
) -> dict:
    if overrides is None:
        loaded = load_classification_rules()
        overrides = loaded["overrides"]
        geography_overrides = (
            loaded["geography_overrides"]
            if geography_overrides is None
            else geography_overrides
        )
        federal_channels = (
            loaded["federal_channels"] if federal_channels is None else federal_channels
        )
        review_metadata = (
            loaded["review_metadata"] if review_metadata is None else review_metadata
        )
        format_overrides = (
            loaded["format_overrides"] if format_overrides is None else format_overrides
        )
        group_overrides = (
            loaded["group_overrides"] if group_overrides is None else group_overrides
        )
        tag_overrides = (
            loaded["tag_overrides"] if tag_overrides is None else tag_overrides
        )
    username = str(channel.get("username") or "").lstrip("@").lower()
    override = overrides.get(username)
    if override is not None and canonical(override) not in TOPICS:
        raise ValueError(f"Unknown topic override for {username}: {override}")
    declared = canonical(
        channel.get("original_subcategory", channel.get("subcategory"))
    )
    inferred = classify_topic(
        channel.get("name") or "", username, channel.get("description") or ""
    )
    if override is not None:
        topic, source = canonical(override), "manual"
    elif declared in TOPICS and declared not in ("general", "other"):
        if (
            declared in TOPICS[inferred["subcategory"]].get("refines", [])
            and inferred["score"] >= 2
        ):
            topic, source = inferred["subcategory"], "heuristic"
        else:
            topic, source = declared, "declared"
    elif inferred["subcategory"] != "other":
        topic, source = inferred["subcategory"], "heuristic"
    elif declared == "general" or canonical(channel.get("category")) == "general":
        topic, source = "general", "fallback"
    elif (
        canonical(channel.get("category")) in TOPICS
        and canonical(channel.get("category")) != "other"
    ):
        topic, source = canonical(channel.get("category")), "fallback"
    else:
        topic, source = "other", "unknown"
    extra_tags = [
        x
        for x in ((tag_overrides or {}).get(username, inferred["tags"]))
        if x != topic and x != "other"
    ]
    group = (group_overrides or {}).get(username, TOPICS[topic]["group"])
    formats = []
    format_evidence = []
    for fmt in TAXONOMY["formats"]:
        for field, text in [
            ("name", _normalize(channel.get("name"))),
            (
                "description",
                _normalize(informative_description(channel.get("description"))),
            ),
        ]:
            found = [k for k in fmt["keywords"] if _matches(k, text, field)]
            if found:
                formats.append(fmt["id"])
                format_evidence.append(field + ":" + found[0])
                break
    if username in (format_overrides or {}):
        formats = format_overrides[username]
        format_evidence = ["manual"]
    reviewed = (review_metadata or {}).get(username)
    stale = bool(
        reviewed
        and (
            reviewed.get("name") != (channel.get("name") or "")
            or reviewed.get("description")
            != informative_description(channel.get("description"))
        )
    )
    return dict(
        **resolve_geography(
            channel, geography_overrides, federal_channels=federal_channels,
            territorial=None if topic == "other" and group == "other_group"
            else topic in TAXONOMY["geography_topics"] or bool(local_news_evidence(
                channel.get("name") or "", channel.get("description") or "")),
        ),
        classification_review_stale=stale,
        classification_version=2,
        topic_group=group,
        topic_group_label=GROUPS[group]["label"],
        topic_path=[group, topic] if topic != "other" else [group],
        broader_topics=TOPICS[topic].get("parent_topics", []),
        topic_granularity="topic"
        if topic != "other"
        else "group"
        if group != "other_group"
        else "unknown",
        publication_formats=formats,
        format_evidence=format_evidence,
        primary_category=topic,
        subcategory=topic,
        topic_category=TOPICS[topic]["section"],
        topic_source=source,
        topic_version=TAXONOMY["version"],
        topic_score=inferred["score"] if source == "heuristic" else None,
        topic_evidence=inferred["evidence"] if source == "heuristic" else [],
        topic_candidates=inferred["candidates"],
        topic_tags=[topic] + extra_tags,
        secondary_topics=extra_tags,
        topic_review_required=stale
        or topic == "other"
        or source == "fallback"
        or (source == "heuristic" and inferred["review_required"]),
    )
